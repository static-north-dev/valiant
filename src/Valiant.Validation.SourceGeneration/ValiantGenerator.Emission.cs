            case "InclusiveBetween":
                return propertyName + " + " + ToLiteral(" must be between " + check.Arguments[0] + " and " + check.Arguments[1] + ".");
            case "ExclusiveBetween":
                return propertyName + " + " + ToLiteral(" must be between " + check.Arguments[0] + " and " + check.Arguments[1] + ", exclusive.");
            case "Satisfies":
            case "SatisfiesAsync":
                return propertyName + " + \" did not satisfy the custom validation predicate.\"";
            default:
                throw new InvalidOperationException("Unsupported check kind '" + check.Kind + "'.");
        }
    }

