using System.Text;

namespace Valiant.SourceGeneration;

internal static class ValiantSourceBuilder
{
    public static void AppendGeneratedFileHeader(StringBuilder builder)
    {
        builder.AppendLine("// <auto-generated />");
        builder.AppendLine("#nullable enable");
    }

    public static void AppendXmlDocumentation(
        StringBuilder builder,
        string? namespaceName,
        int indentLevel,
        string summary,
        string? returns = null,
        params (string Name, string Description)[] parameters)
    {
        AppendIndent(builder, indentLevel, namespaceName);
        builder.AppendLine("/// <summary>");
        AppendIndent(builder, indentLevel, namespaceName);
        builder.Append("/// ").AppendLine(summary);
        AppendIndent(builder, indentLevel, namespaceName);
        builder.AppendLine("/// </summary>");

        foreach (var parameter in parameters)
        {
            AppendIndent(builder, indentLevel, namespaceName);
            builder.Append("/// <param name=\"")
                .Append(parameter.Name)
                .Append("\">")
                .Append(parameter.Description)
                .AppendLine("</param>");
        }

        if (returns is not null)
        {
            AppendIndent(builder, indentLevel, namespaceName);
            builder.Append("/// <returns>").Append(returns).AppendLine("</returns>");
        }
    }

    public static void AppendIndent(StringBuilder builder, int level, string? namespaceName)
    {
        var adjustedLevel = namespaceName is null ? level : level + 1;
        builder.Append(' ', adjustedLevel * 4);
    }

    public static int AppendContainingTypeDeclarations<TContainingType>(
        StringBuilder builder,
        string? namespaceName,
        IEnumerable<TContainingType> containingTypes,
        Func<TContainingType, string> getModifier,
        Func<TContainingType, string> getKeyword,
        Func<TContainingType, string> getName)
    {
        var depth = 0;
        foreach (var containingType in containingTypes)
        {
            AppendIndent(builder, depth, namespaceName);
            builder.Append(getModifier(containingType))
                .Append("partial ")
                .Append(getKeyword(containingType))
                .Append(' ')
                .Append(getName(containingType))
                .AppendLine();
            AppendIndent(builder, depth, namespaceName);
            builder.AppendLine("{");
            depth++;
        }

        return depth;
    }

    public static void AppendContainingTypeClosures(StringBuilder builder, string? namespaceName, int containingTypeCount)
    {
        for (var depth = containingTypeCount - 1; depth >= 0; depth--)
        {
            AppendIndent(builder, depth, namespaceName);
            builder.AppendLine("}");
        }
    }
}
