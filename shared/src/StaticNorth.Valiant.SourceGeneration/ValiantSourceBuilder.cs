using System.Globalization;
using System.Text;

namespace StaticNorth.Valiant.SourceGeneration;

internal static class ValiantSourceBuilder
{
    public static void AppendGeneratedFileHeader(StringBuilder builder)
    {
        builder.AppendLine("// <auto-generated />");
        builder.AppendLine("#nullable enable");
    }

    public static void AppendAssemblyRegistration(
        StringBuilder builder,
        string assemblyName,
        string className,
        string extensionClass,
        string methodName,
        params (string Parameters, string Arguments)[] overloads)
    {
        builder.AppendLine();
        builder.Append("namespace ");
        AppendAssemblyNamespace(builder, assemblyName);
        builder.AppendLine();
        builder.AppendLine("{");
        builder.AppendLine("    /// <summary>Registers Valiant services from this assembly.</summary>");
        builder.Append("    public static class ").AppendLine(className);
        builder.AppendLine("    {");
        foreach (var (parameters, arguments) in overloads)
        {
            builder.AppendLine("        /// <summary>Adds the services generated in this assembly.</summary>");
            builder.Append("        public static global::Microsoft.Extensions.DependencyInjection.IServiceCollection ")
                .Append(methodName).Append("(global::Microsoft.Extensions.DependencyInjection.IServiceCollection services")
                .Append(parameters).AppendLine(") =>");
            builder.Append("            ").Append(extensionClass).Append('.').Append(methodName)
                .Append("(services").Append(arguments).AppendLine(");");
        }

        builder.AppendLine("    }");
        builder.AppendLine("}");
    }

    public static StringBuilder AppendAssemblyNamespace(StringBuilder builder, string assemblyName)
    {
        builder.Append("StaticNorth.Valiant.Generated");
        foreach (var segment in assemblyName.Split('.'))
        {
            builder.Append(".Assembly_");
            foreach (var character in segment)
            {
                if (character is >= 'A' and <= 'Z' or >= 'a' and <= 'z' or >= '0' and <= '9')
                {
                    builder.Append(character);
                }
                else
                {
                    builder.Append('_').Append(((int)character).ToString("X4", CultureInfo.InvariantCulture));
                }
            }
        }
        return builder;
    }

    public static void AppendXmlDocumentation(
        StringBuilder builder,
        string? namespaceName,
        int indentLevel,
        string summary,
        string? returns = null,
        params (string Name, string Description)[] parameters)
    {
        AppendIndent(builder, indentLevel, namespaceName);
        builder.AppendLine("/// <summary>");
        AppendIndent(builder, indentLevel, namespaceName);
        builder.Append("/// ").AppendLine(summary);
        AppendIndent(builder, indentLevel, namespaceName);
        builder.AppendLine("/// </summary>");

        foreach (var parameter in parameters)
        {
            AppendIndent(builder, indentLevel, namespaceName);
            builder.Append("/// <param name=\"")
                .Append(parameter.Name)
                .Append("\">")
                .Append(parameter.Description)
                .AppendLine("</param>");
        }

        if (returns is not null)
        {
            AppendIndent(builder, indentLevel, namespaceName);
            builder.Append("/// <returns>").Append(returns).AppendLine("</returns>");
        }
    }

    public static void AppendIndent(StringBuilder builder, int level, string? namespaceName)
    {
        var adjustedLevel = namespaceName is null ? level : level + 1;
        builder.Append(' ', adjustedLevel * 4);
    }

    public static int AppendContainingTypeDeclarations<TContainingType>(
        StringBuilder builder,
        string? namespaceName,
        IEnumerable<TContainingType> containingTypes,
        Func<TContainingType, string> getModifier,
        Func<TContainingType, string> getKeyword,
        Func<TContainingType, string> getName)
    {
        var depth = 0;
        foreach (var containingType in containingTypes)
        {
            AppendIndent(builder, depth, namespaceName);
            builder.Append(getModifier(containingType))
                .Append("partial ")
                .Append(getKeyword(containingType))
                .Append(' ')
                .Append(getName(containingType))
                .AppendLine();
            AppendIndent(builder, depth, namespaceName);
            builder.AppendLine("{");
            depth++;
        }

        return depth;
    }

    public static void AppendContainingTypeClosures(StringBuilder builder, string? namespaceName, int containingTypeCount)
    {
        for (var depth = containingTypeCount - 1; depth >= 0; depth--)
        {
            AppendIndent(builder, depth, namespaceName);
            builder.AppendLine("}");
        }
    }
}
